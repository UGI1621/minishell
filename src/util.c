#include "minishell.h"

int	is_wspace(char c)
{
	return (c == 8 || c == 9 || c == 10 || c == 11
		|| c == 12 || c == 13 || c == 32);
}

int	is_quote(char c)
{
	return (c == '\'' || c == '\"');
}

int	is_cutsign(char c)
{
	return (c == '|' || c == '<' || c == '>');
}
